import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { ArcRotateCamera } from "@babylonjs/core/Cameras/arcRotateCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { DirectionalLight } from "@babylonjs/core/Lights/directionalLight";
import { Vector3, Color4 } from "@babylonjs/core/Maths/math";
import { MeshBuilder } from "@babylonjs/core/Meshes/meshBuilder";
import { loadContainer, instantiate } from "../game/models";
import { Rig } from "../anim/rig";
import { Retarget } from "../anim/retarget";
import { WolfAnimator, WOLF_ATTACKS, loadWolfClips } from "../anim/wolfAnimator";
import { HumanAnimator, HUMAN_BONES } from "../anim/humanAnimator";

// Dev-only animation check page.
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true, { preserveDrawingBuffer: true });
const scene = new Scene(engine);
scene.useRightHandedSystem = true;
scene.clearColor = new Color4(0.55, 0.6, 0.68, 1);
const cam = new ArcRotateCamera("c", Math.PI / 2, 1.3, 7, new Vector3(0, 1.1, 0), scene);
cam.attachControl(canvas, true);
new HemisphericLight("h", new Vector3(0.2, 1, 0.3), scene).intensity = 0.9;
const d = new DirectionalLight("d", new Vector3(-0.4, -1, -0.6), scene);
d.intensity = 1.6;
const g = MeshBuilder.CreateGround("g", { width: 20, height: 20 }, scene);
void g;
const w = window as unknown as Record<string, unknown>;
const q = new URLSearchParams(location.search);
const wolfId = q.get("wolf") ?? "normal";
const state = { fwd: 0, right: 0, grounded: true, pitch: 0, hfwd: 0, hleft: 0, yaw: 0 };
w.state = state;
(async () => {
    const lib = await loadWolfClips("../assets/");
    const wc = await loadContainer(scene, `../assets/models/wolves/${wolfId}_wolf.glb`);
    const wolf = instantiate(scene, wc, 2.15, "wolf");
    wolf.root.position.x = -1.2;
    const rig = new Rig(wolf.gltf, lib.header.bones);
    const rt = Retarget.create(rig, lib)!;
    const legW = rt.legLen / wolf.scale;
    const wa = new WolfAnimator(lib, rt, legW);
    if (rt.facingFlip) wolf.gltf.rotation.y = Math.PI;
    const hc = await loadContainer(scene, `../assets/models/humans/human_onculer.glb`);
    const human = instantiate(scene, hc, 1.84, "human");
    human.root.position.x = 1.2;
    const hrig = new Rig(human.gltf, HUMAN_BONES);
    const ha = new HumanAnimator(hrig, human.scale);
    const gc = await loadContainer(scene, `../assets/models/weapons/wolfstrike_m4a1.glb`);
    const gun = gc.instantiateModelsToScene((n) => "gun:" + n, false).rootNodes[0];
    gun.parent = human.gltf;
    (gun as any).scaling.setAll(0.8 / 0.98 * human.scale);
    w.info = { flip: rt.facingFlip, legLen: rt.legLen, legW, unitsPerM: wolf.scale, bones: rig.bones.length, hbones: hrig.bones.length };
    w.play = (n: keyof typeof WOLF_ATTACKS) => wa.play(WOLF_ATTACKS[n]);
    w.playClip = (clip: string, from?: number, to?: number) => wa.play({ clip, from, to });
    w.die = () => { wa.play({ clip: "hit_l", to: 42, hold: true, rate: 0.9 }); ha.die(); };
    w.jump = () => wa.jump();
    w.cam = cam;
    let t = 0;
    scene.onBeforeRenderObservable.add(() => {
        const dt = Math.min(0.05, engine.getDeltaTime() / 1000);
        t += dt;
        wolf.root.rotation.y = state.yaw;
        human.root.rotation.y = state.yaw;
        wa.update(dt, state.fwd, state.right, state.grounded);
        ha.update(dt, state.hfwd, state.hleft, state.pitch, state.grounded);
        (gun as any).position.copyFrom(ha.gun.origin);
        (gun as any).rotationQuaternion = ha.gun.rot.multiply(new (ha.gun.rot.constructor as any)(0, 0.7071, 0, 0.7071));
    });
    w.ready = true;
})().catch((e) => { console.error(e); w.err = String(e); w.ready = true; });
engine.runRenderLoop(() => scene.render());
